"""
Media Content & Market Index Publisher for RMon Platform.
Автономная генерация профессиональных аналитических постов для Telegram-канала / блога:
- Еженедельные срезы индексов цен вторичного рынка (GPU, Apple, Консоли)
- Разборы типовых уловок продавцов и памятки безопасной покупки
- Интеграция органического перелива в Telegram-бот @AvitoRadarBot и CPA-виджеты
"""
import re
